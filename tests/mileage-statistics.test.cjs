const test = require('node:test')
const assert = require('node:assert/strict')
const row = (date, vehicleMileage) => ({ vehicleControl: true, vehicleId: 'v', date, vehicleMileage, status: 'Completado' })
test('distributes distance across months and averages only fully covered past months', async () => {
 const { mileageStatistics } = await import('../src/domain/vehicles/mileage-statistics.mjs')
 const result = mileageStatistics([row('2026-09-01', 1000), row('2026-10-05', 1340)], 'v', '2026-10-13')
 assert.equal(result.average, 300)
 assert.equal(result.completeMonths, 1)
 assert.equal(result.rows[0].km, 40)
 assert.equal(result.rows[0].complete, false)
 assert.equal(result.rows[1].days, 30)
})
test('excludes decreasing readings and does not bridge affected intervals', async () => {
 const { mileageStatistics } = await import('../src/domain/vehicles/mileage-statistics.mjs')
 const result = mileageStatistics([row('2026-09-01', 1000), row('2026-09-08', 900), row('2026-09-15', 1500)], 'v', '2026-10-13')
 assert.equal(result.warnings, 1)
 assert.equal(result.average, null)
 assert.equal(result.rows.length, 0)
})
test('conflicting same-day readings and future readings cannot inflate totals', async () => {
 const { mileageStatistics } = await import('../src/domain/vehicles/mileage-statistics.mjs')
 const result = mileageStatistics([row('2026-09-01', 100), row('2026-09-01', 200), row('2026-09-08', 300), row('2026-11-01', 900)], 'v', '2026-10-13')
 assert.equal(result.warnings, 1)
 assert.equal(result.rows.length, 0)
})
