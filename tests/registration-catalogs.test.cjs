const test=require('node:test'),assert=require('node:assert/strict')
test('official catalog: distinct localities, locality-specific neighborhoods and explicit incomplete coverage',async()=>{
  const c=await import('../shared/registration/catalogs.mjs')
  assert.ok(c.cities.length>400);assert.equal(new Set(c.cityOptions).size,c.cityOptions.length)
  assert.equal(c.cityFor('cORdoba').name,'Córdoba')
  assert.ok(c.neighborhoodsFor('Córdoba').length>400)
  assert.ok(c.neighborhoodsFor('Villa Allende').includes('La Amalia'))
  assert.equal(c.neighborhoodsFor('La Calera').length,0)
  assert.match(c.neighborhoodCoverage('La Calera'),/no contamos/)
  const {stepsFor}=await import('../shared/registration/schema.mjs')
  const fields=stepsFor('residencial',{city:'Villa Allende'}).flatMap(s=>s.fields)
  assert.equal(fields.find(f=>f.id==='neighborhood').options.includes('La Amalia'),true)
  assert.equal(fields.find(f=>f.id==='neighborhood').options.includes('Nueva Córdoba'),false)
  assert.equal(fields.find(f=>f.id==='neighborhood').options.at(-1),c.OTHER_NEIGHBORHOOD)
})
test('submission validates city/neighborhood pair, explicit exception and CBU/bank match',async()=>{
  const c=await import('../shared/registration/catalogs.mjs'),{validate}=await import('../shared/registration/validate.mjs')
  let r=validate('residencial',{city:'Córdoba',neighborhood:'Inventado'})
  assert.ok(r.errors.neighborhood)
  r=validate('residencial',{city:'Cordoba',neighborhood:'centro'})
  assert.equal(r.errors.city,undefined);assert.equal(r.errors.neighborhood,undefined);assert.equal(r.values.city,'Córdoba');assert.equal(r.values.neighborhood,'Centro')
  r=validate('residencial',{city:'La Calera',neighborhood:c.OTHER_NEIGHBORHOOD})
  assert.ok(r.errors.neighborhoodOther)
  r=validate('residencial',{city:'La Calera',neighborhood:c.OTHER_NEIGHBORHOOD,neighborhoodOther:'Barrio por verificar'})
  assert.equal(r.errors.neighborhoodOther,undefined)
  r=validate('residencial',{city:'Ciudad inexistente',neighborhood:'Centro'})
  assert.ok(r.errors.city)
  const cbu='0720000700000000000017',bank=c.bankForCbu(cbu).name
  r=validate('residencial',{paymentMethod:'Débito CBU',cbu,bank})
  assert.equal(r.errors.cbu,undefined);assert.equal(r.errors.bank,undefined)
  assert.ok(validate('residencial',{paymentMethod:'Débito CBU',cbu,bank:c.bankForCbu('020').name}).errors.bank)
  assert.ok(validate('residencial',{paymentMethod:'Débito CBU',cbu,bank:'Billetera no bancaria'}).errors.bank)
  assert.ok(validate('residencial',{paymentMethod:'Débito CBU',cbu:'0000000000000000000000',bank}).errors.cbu)
})
